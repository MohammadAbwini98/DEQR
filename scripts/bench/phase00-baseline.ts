/**
 * Phase 00 — Baseline Audit Harness
 *
 * Drives the real shipping modules (`session-manager` constants, `container`,
 * `fountain-encoder`, `protocol`, and the browser-safe `ReceiverSession`) over a
 * size sweep and an extension matrix, recording per-stage timings, byte counts,
 * and memory growth.
 *
 * It exists to answer two questions with runtime evidence rather than source
 * reading:
 *   1. exactly where DEQR stops accepting large files, and why;
 *   2. whether an identical byte sequence transfers differently when only its
 *      filename extension changes.
 *
 * Payload safety: no transferred bytes, no absolute source paths, and no
 * cryptographic key material are written to the evidence file. Corpora are
 * deterministic synthetic bytes generated by this script.
 *
 *   node node_modules/vite-node/vite-node.mjs scripts/bench/phase00-baseline.ts -- --help
 */

