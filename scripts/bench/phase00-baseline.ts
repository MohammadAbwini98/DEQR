function usage(): string {
  return [
    'Phase 00 baseline harness',
    '',
    '  --mode all|capacity|extension|boundary   (default all)',
    '  --sizes 1,16,32,48,64           MiB sweep for the capacity mode',
    '  --samples 3                     repeats of the extension matrix',
    '  --decode-max-mib 32             largest container to decode end to end',
    '  --extension-size-mib 4          payload size used for the extension matrix',
    '  --label baseline                evidence label',
    '  --output <path under .local-run/bench/>',
  ].join('\n');
}

function positiveInteger(value: string | undefined, name: string, fallback: number): number {
  if (value === undefined) return fallback;
  const parsed = Number(value);
  if (!Number.isInteger(parsed) || parsed < 1 || parsed > 4_096) {
    throw new Error(`${name} must be an integer between 1 and 4096.`);
  }
  return parsed;
}

function parseOptions(argumentsList: string[]): Options {
  const values = new Map<string, string>();
  for (let index = 0; index < argumentsList.length; index += 1) {
    const argument = argumentsList[index];
    if (argument === '--help' || argument === '-h') {
      console.log(usage());
      process.exit(0);
    }
    if (!argument.startsWith('--')) throw new Error(`Unexpected argument: ${argument}`);
    const value = argumentsList[index + 1];
    if (value === undefined || value.startsWith('--')) throw new Error(`Missing value for ${argument}`);
    values.set(argument, value);
    index += 1;
  }

  const label = values.get('--label') ?? 'baseline';
  if (!/^[a-z0-9][a-z0-9._-]*$/i.test(label)) {
    throw new Error('--label may contain only letters, numbers, dots, underscores, and hyphens.');
  }

  const mode = (values.get('--mode') ?? 'all') as Mode;
  if (!['all', 'capacity', 'extension', 'boundary'].includes(mode)) {
    throw new Error('--mode must be all, capacity, extension, or boundary.');
  }

  const sizesMib = (values.get('--sizes') ?? DEFAULT_SIZES_MIB.join(','))
    .split(',')
    .map((entry) => Number(entry.trim()))
    .filter((entry) => entry > 0);
  if (!sizesMib.length || sizesMib.some((entry) => !Number.isInteger(entry) || entry > 4_096)) {
    throw new Error('--sizes must be a comma-separated list of MiB integers up to 4096.');
  }

  return {
    mode,
    sizesMib,
    samples: positiveInteger(values.get('--samples'), '--samples', 3),
    decodeMaxMib: positiveInteger(values.get('--decode-max-mib'), '--decode-max-mib', 32),
    extensionSizeMib: positiveInteger(values.get('--extension-size-mib'), '--extension-size-mib', 4),
    output: values.get('--output') ?? `.local-run/bench/phase00-baseline-${label}.json`,
    label,
  };
}

function resolveOutputPath(rawOutput: string): string {
  const allowedRoot = resolve(process.cwd(), '.local-run', 'bench');
  const output = resolve(process.cwd(), rawOutput);
  const outputRelative = relative(allowedRoot, output);
  if (outputRelative.startsWith('..') || outputRelative === '' || outputRelative.includes(':')) {
    throw new Error('Benchmark output must be a file below .local-run/bench/.');
  }
  return output;
}

/* ------------------------------------------------------------------ corpora */

/** Deterministic high-entropy bytes. gzip cannot shrink these. */
function randomBytes(length: number, seed: number): Buffer {
  const bytes = Buffer.allocUnsafe(length);
  let state = seed >>> 0;
  for (let index = 0; index < length; index += 1) {
    state = (Math.imul(state, 1664525) + 1013904223) >>> 0;
    bytes[index] = state >>> 24;
  }
  return bytes;
}

const WORDS = [
  'transfer', 'optical', 'fountain', 'segment', 'container', 'protocol', 'receiver',
  'sender', 'integrity', 'checksum', 'stream', 'bounded', 'window', 'symbol', 'repair',
  'systematic', 'offline', 'verified', 'throughput', 'baseline',
];

/** Deterministic text-like bytes with real redundancy, so gzip has something to find. */
function textBytes(length: number, seed: number): Buffer {
  const bytes = Buffer.alloc(length, 0x20);
  let state = seed >>> 0;
  let offset = 0;
  let column = 0;
  while (offset < length) {
    state = (Math.imul(state, 1664525) + 1013904223) >>> 0;
    const word = WORDS[(state >>> 16) % WORDS.length];
    const chunk = column > 68 ? `${word}\n` : `${word} `;
    if (offset + chunk.length > length) break;
    column = column > 68 ? 0 : column + chunk.length;
    offset += bytes.write(chunk, offset, 'latin1');
  }
  return bytes;
}

function buildCorpus(corpus: Corpus, length: number, seed: number): Buffer {
  return corpus === 'text' ? textBytes(length, seed) : randomBytes(length, seed);
}

/* ---------------------------------------------------------------- utilities */

function snapshot(): MemorySample {
  const usage = process.memoryUsage();
  return {
    rssBytes: usage.rss,
    heapUsedBytes: usage.heapUsed,
    externalBytes: usage.external,
    arrayBuffersBytes: usage.arrayBuffers,
  };
}

function peak(samples: MemorySample[]): MemorySample {
  return {
    rssBytes: Math.max(...samples.map((entry) => entry.rssBytes)),
    heapUsedBytes: Math.max(...samples.map((entry) => entry.heapUsedBytes)),
    externalBytes: Math.max(...samples.map((entry) => entry.externalBytes)),
    arrayBuffersBytes: Math.max(...samples.map((entry) => entry.arrayBuffersBytes)),
  };
}

function timed<T>(operation: () => T): { value: T; ms: number } {
  const start = performance.now();
  const value = operation();
  return { value, ms: performance.now() - start };
}

async function timedAsync<T>(operation: () => Promise<T>): Promise<{ value: T; ms: number }> {
  const start = performance.now();
  const value = await operation();
  return { value, ms: performance.now() - start };
}

function bytesPerSecond(bytes: number, ms: number): number {
  return ms > 0 ? bytes / (ms / 1_000) : 0;
}

function errorMessage(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}

/**
 * Compressibility measured the way Phase 08 will have to measure it: from
 * bounded samples of the actual bytes, never from the extension.
 */
function sampleCompressibility(source: Buffer): {
  compressionInputBytes: number;
  compressionOutputBytes: number;
  compressionMs: number;
  sampledRatio: number;
} {
  const sampleSize = Math.min(source.length, 1 * MIB);
  const offsets = [
    0,
    Math.max(0, Math.floor(source.length / 2) - sampleSize),
    Math.max(0, source.length - sampleSize),
  ];
  const unique = [...new Set(offsets)];
  let input = 0;
  let output = 0;
  const start = performance.now();
  for (const offset of unique) {
    const slice = source.subarray(offset, offset + sampleSize);
    input += slice.length;
    output += gzipSync(slice, { level: 6 }).length;
  }
  const compressionMs = performance.now() - start;
  return {
    compressionInputBytes: input,
    compressionOutputBytes: output,
    compressionMs,
    sampledRatio: input > 0 ? output / input : 1,
  };
}

