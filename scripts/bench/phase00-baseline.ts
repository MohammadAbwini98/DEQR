interface CapacityScenario {
  corpus: Corpus;
  sizeMib: number;
  sizeBytes: number;
  filename: string;
  fileReadMs: number;
  fileReadBytesPerSec: number;
  hashMs: number;
  hashBytesPerSec: number;
  compressionInputBytes: number;
  compressionOutputBytes: number;
  compressionMs: number;
  sampledCompressionRatio: number;
  containerSerializeMs: number;
  containerBytes: number;
  containerOverheadBytes: number;
  selectionGate: 'accepted' | 'rejected-raw-size' | 'rejected-serialized-size';
  selectionGateThresholdBytes: number;
  encoderConstructed: boolean;
  encoderError: string | null;
  encoderInitMs: number;
  blockCount: number | null;
  frameBytes: number | null;
  encodeSampleFrames: number;
  encodeSampleMs: number;
  fountainEncodeSymbolsPerSec: number;
  opticalPayloadBytesPerSec: number;
  projectedSystematicPassSeconds: number | null;
  decodeAttempted: boolean;
  decodeSkippedReason: string | null;
  uniqueFramesAccepted: number;
  duplicatesDropped: number;
  framesRejected: number;
  pwaReceiveMs: number;
  fountainDecodeSymbolsPerSec: number;
  verifyMs: number;
  verifyBytesPerSec: number;
  verifyOutcome: string;
  endToEndCpuMs: number;
  memoryBefore: MemorySample;
  memoryPeak: MemorySample;
  peakRssOverSizeRatio: number;
}

async function runCapacityScenario(
  corpus: Corpus,
  sizeMib: number,
  corpusDir: string,
  decodeMaxBytes: number,
): Promise<CapacityScenario> {
  const sizeBytes = sizeMib * MIB;
  const filename = `phase00-${corpus}-${sizeMib}mib.bin`;
  const filePath = resolve(corpusDir, filename);

  if (!fs.existsSync(filePath) || fs.statSync(filePath).size !== sizeBytes) {
    const generated = buildCorpus(corpus, sizeBytes, (SESSION_ID ^ sizeBytes ^ (corpus === 'text' ? 1 : 2)) >>> 0);
    fs.writeFileSync(filePath, generated);
    generated.fill(0);
  }

  const memoryBefore = snapshot();
  const memorySamples: MemorySample[] = [memoryBefore];
  const startedAt = performance.now();

  // Stage 1 — whole-file read. This is exactly what `SessionManager.selectFile` does.
  const read = timed(() => fs.readFileSync(filePath));
  const source = read.value;
  memorySamples.push(snapshot());

  // Stage 2 — SHA-256 over the whole buffer.
  const hash = timed(() => computeSha256(source));
  memorySamples.push(snapshot());

  // Stage 3 — sampled compressibility. The shipping sender never calls this.
  const compressibility = sampleCompressibility(source);

  // Stage 4 — container serialization: a second whole-file allocation and copy.
  const container = timed(() => serializeContainer({
    metadata: {
      protocolVersion: PROTOCOL_VERSION,
      filename,
      mimeType: MIME_TYPE,
      originalSize: source.length,
      compressed: false,
      encrypted: false,
      timestamp: 0,
      sha256: hash.value,
    },
    payload: source,
  }));
  const containerBytes = container.value;
  memorySamples.push(snapshot());

  // Stage 5 — the two shipping selection gates, in the order the sender applies them.
  const selectionGate: CapacityScenario['selectionGate'] =
    sizeBytes >= V1_MAX_SERIALIZED_CONTAINER_BYTES
      ? 'rejected-raw-size'
      : containerBytes.length > V1_MAX_SERIALIZED_CONTAINER_BYTES
        ? 'rejected-serialized-size'
        : 'accepted';

  // Stage 6 — encoder construction. Run regardless of the gate, so the
  // underlying protocol failure is observed rather than inferred from it.
  const encoderInit = timed((): { encoder: FountainEncoder | null; error: string | null } => {
    try {
      return {
        encoder: new FountainEncoder(containerBytes, V1_FOUNTAIN_BLOCK_SIZE_BYTES, SESSION_ID),
        error: null,
      };
    } catch (error) {
      return { encoder: null, error: errorMessage(error) };
    }
  });
  memorySamples.push(snapshot());

  const active = encoderInit.value.encoder;
  const encoderError = encoderInit.value.error;
  const blockCount = active ? active.getBlockCount() : null;

  // Stage 7 — frame generation rate over a bounded sample.
  let encodeSampleFrames = 0;
  let encodeSampleMs = 0;
  let frameBytes: number | null = null;
  if (active) {
    const target = Math.min(ENCODE_SAMPLE_FRAMES, blockCount ?? 0);
    const start = performance.now();
    for (let index = 0; index < target; index += 1) {
      frameBytes = serializeFrame(active.nextFrame()).length;
      encodeSampleFrames += 1;
    }
    encodeSampleMs = performance.now() - start;
  }
  memorySamples.push(snapshot());

  const projectedSystematicPassSeconds = blockCount === null ? null : blockCount / SHIPPING_TRANSFER_FPS;

  // Stage 8 — receiver. Bounded by --decode-max-mib because the shipping
  // receiver holds the entire transfer in memory, and this harness must not be
  // what decides how much of that a workstation can survive.
  let decodeAttempted = false;
  let decodeSkippedReason: string | null = null;
  let uniqueFramesAccepted = 0;
  let duplicatesDropped = 0;
  let framesRejected = 0;
  let pwaReceiveMs = 0;
  let verifyMs = 0;
  let verifyOutcome = 'not-attempted';

  if (!active) {
    decodeSkippedReason = 'sender never produced a frame stream';
  } else if (containerBytes.length > decodeMaxBytes) {
    decodeSkippedReason = `container ${containerBytes.length} bytes exceeds --decode-max-mib`;
  } else {
    decodeAttempted = true;
    // The sample above already consumed sequence numbers, so restart the stream
    // to give the receiver a systematic-first pass.
    const streamEncoder = new FountainEncoder(containerBytes, V1_FOUNTAIN_BLOCK_SIZE_BYTES, SESSION_ID);
    const receiver = new ReceiverSession();
    let state = receiver.snapshot();
    const maxFrames = (blockCount ?? 0) * 2 + 128;
    let generated = 0;
    const start = performance.now();
    while (state.state !== 'VERIFYING' && generated < maxFrames) {
      const raw = new Uint8Array(serializeFrame(streamEncoder.nextFrame()));
      generated += 1;
      const previousDuplicates = state.duplicates;
      state = receiver.receive(raw);
      if (state.state === 'FAILED') {
        framesRejected += 1;
        break;
      }
      if (state.duplicates > previousDuplicates) duplicatesDropped += 1;
      else uniqueFramesAccepted += 1;
    }
    pwaReceiveMs = performance.now() - start;
    memorySamples.push(snapshot());

    const verification = await timedAsync(() => receiver.verify());
    verifyMs = verification.ms;
    verifyOutcome = verification.value.state === 'COMPLETE'
      ? 'COMPLETE'
      : `${verification.value.state}:${verification.value.error?.code ?? 'unknown'}`;
    memorySamples.push(snapshot());
    receiver.reset();
  }

  const endToEndCpuMs = performance.now() - startedAt;
  const memoryPeak = peak(memorySamples);
  source.fill(0);
  containerBytes.fill(0);

  return {
    corpus,
    sizeMib,
    sizeBytes,
    filename,
    fileReadMs: read.ms,
    fileReadBytesPerSec: bytesPerSecond(sizeBytes, read.ms),
    hashMs: hash.ms,
    hashBytesPerSec: bytesPerSecond(sizeBytes, hash.ms),
    compressionInputBytes: compressibility.compressionInputBytes,
    compressionOutputBytes: compressibility.compressionOutputBytes,
    compressionMs: compressibility.compressionMs,
    sampledCompressionRatio: compressibility.sampledRatio,
    containerSerializeMs: container.ms,
    containerBytes: containerBytes.length,
    containerOverheadBytes: containerBytes.length - sizeBytes,
    selectionGate,
    selectionGateThresholdBytes: V1_MAX_SERIALIZED_CONTAINER_BYTES,
    encoderConstructed: active !== null,
    encoderError,
    encoderInitMs: encoderInit.ms,
    blockCount,
    frameBytes,
    encodeSampleFrames,
    encodeSampleMs,
    fountainEncodeSymbolsPerSec: encodeSampleMs > 0 ? encodeSampleFrames / (encodeSampleMs / 1_000) : 0,
    opticalPayloadBytesPerSec: SHIPPING_TRANSFER_FPS * V1_FOUNTAIN_BLOCK_SIZE_BYTES,
    projectedSystematicPassSeconds,
    decodeAttempted,
    decodeSkippedReason,
    uniqueFramesAccepted,
    duplicatesDropped,
    framesRejected,
    pwaReceiveMs,
    fountainDecodeSymbolsPerSec: pwaReceiveMs > 0 ? uniqueFramesAccepted / (pwaReceiveMs / 1_000) : 0,
    verifyMs,
    verifyBytesPerSec: bytesPerSecond(sizeBytes, verifyMs),
    verifyOutcome,
    endToEndCpuMs,
    memoryBefore,
    memoryPeak,
    peakRssOverSizeRatio: memoryPeak.rssBytes / sizeBytes,
  };
}

/* ----------------------------------------------------------- extension mode */

interface ExtensionSample {
  extension: string;
  filename: string;
  filenameBytes: number;
  blockedBySender: boolean;
  containerBytes: number;
  blockCount: number;
  frameBytes: number | null;
  /**
   * SHA-256 of the serialized container with the variable-length filename field
   * removed. Identical values across extensions prove that nothing downstream
   * of the filename can differ.
   */
  containerDigestExcludingFilename: string;
  frameStreamDigest: string;
  framesGenerated: number;
  hashMs: number;
  containerSerializeMs: number;
  encodeMs: number;
  receiveMs: number;
  verifyMs: number;
  endToEndMs: number;
  verifyOutcome: string;
}

function containerDigestExcludingFilename(container: Buffer, filenameBytes: number): string {
  // Layout: magic(4) version(2) filenameLength(2) filename(n) ...
  const head = container.subarray(0, 8);
  const tail = container.subarray(8 + filenameBytes);
  return createHash('sha256').update(head).update(tail).digest('hex');
}

async function runExtensionSample(source: Buffer, extension: string, filename: string): Promise<ExtensionSample> {
  const filenameBytes = Buffer.byteLength(filename, 'utf-8');
  const blockedBySender = isBlockedExtension(filename);
  const startedAt = performance.now();

  const hash = timed(() => computeSha256(source));
  const container = timed(() => serializeContainer({
    metadata: {
      protocolVersion: PROTOCOL_VERSION,
      filename,
      mimeType: MIME_TYPE,
      originalSize: source.length,
      compressed: false,
      encrypted: false,
      timestamp: 0,
      sha256: hash.value,
    },
    payload: source,
  }));

  const digest = containerDigestExcludingFilename(container.value, filenameBytes);

  const encoderInit = timed(() => new FountainEncoder(container.value, V1_FOUNTAIN_BLOCK_SIZE_BYTES, SESSION_ID));
  const encoder = encoderInit.value;
  const blockCount = encoder.getBlockCount();

  const receiver = new ReceiverSession();
  const streamHash = createHash('sha256');
  let state = receiver.snapshot();
  let frameBytes: number | null = null;
  let encodeMs = 0;
  let receiveMs = 0;
  const maxFrames = blockCount * 2 + 128;
  let generated = 0;

  while (state.state !== 'VERIFYING' && generated < maxFrames) {
    const encodeStart = performance.now();
    const raw = serializeFrame(encoder.nextFrame());
    encodeMs += performance.now() - encodeStart;
    streamHash.update(raw);
    frameBytes = raw.length;
    generated += 1;

    const receiveStart = performance.now();
    state = receiver.receive(new Uint8Array(raw));
    receiveMs += performance.now() - receiveStart;
    if (state.state === 'FAILED') break;
  }

  const verification = await timedAsync(() => receiver.verify());
  const verifyOutcome = verification.value.state === 'COMPLETE'
    ? 'COMPLETE'
    : `${verification.value.state}:${verification.value.error?.code ?? 'unknown'}`;
  receiver.reset();

  return {
    extension,
    filename,
    filenameBytes,
    blockedBySender,
    containerBytes: container.value.length,
    blockCount,
    frameBytes,
    containerDigestExcludingFilename: digest,
    frameStreamDigest: streamHash.digest('hex'),
    framesGenerated: generated,
    hashMs: hash.ms,
    containerSerializeMs: container.ms,
    encodeMs: encodeMs + encoderInit.ms,
    receiveMs,
    verifyMs: verification.ms,
    endToEndMs: performance.now() - startedAt,
    verifyOutcome,
  };
}

/* ------------------------------------------------------------ boundary mode */

interface BoundaryProbe {
  filename: string;
  containerHeaderBytes: number;
  v1MaxSerializedContainerBytes: number;
  largestAcceptedSourceBytes: number;
  largestAcceptedSourceMib: number;
  atCeiling: { sourceBytes: number; containerBytes: number; gate: string; blockCount: number | null; encoderError: string | null };
  oneByteOver: { sourceBytes: number; containerBytes: number; gate: string; blockCount: number | null; encoderError: string | null };
  rawSizeGateRejectsAtOrAbove: number;
  nominal32MibRejected: boolean;
}

function containerHeaderBytes(filename: string): number {
  return serializeContainer({
    metadata: {
      protocolVersion: PROTOCOL_VERSION,
      filename,
      mimeType: MIME_TYPE,
      originalSize: 0,
      compressed: false,
      encrypted: false,
      timestamp: 0,
      sha256: Buffer.alloc(32),
    },
    payload: Buffer.alloc(0),
  }).length;
}

function probeSourceSize(filename: string, sourceBytes: number): BoundaryProbe['atCeiling'] {
  const source = Buffer.alloc(sourceBytes, 0xa5);
  try {
    const container = serializeContainer({
      metadata: {
        protocolVersion: PROTOCOL_VERSION,
        filename,
        mimeType: MIME_TYPE,
        originalSize: source.length,
        compressed: false,
        encrypted: false,
        timestamp: 0,
        sha256: computeSha256(source),
      },
      payload: source,
    });

    const gate = sourceBytes >= V1_MAX_SERIALIZED_CONTAINER_BYTES
      ? 'rejected-raw-size'
      : container.length > V1_MAX_SERIALIZED_CONTAINER_BYTES
        ? 'rejected-serialized-size'
        : 'accepted';

    let blockCount: number | null = null;
    let encoderError: string | null = null;
    try {
      blockCount = new FountainEncoder(container, V1_FOUNTAIN_BLOCK_SIZE_BYTES, SESSION_ID).getBlockCount();
    } catch (error) {
      encoderError = errorMessage(error);
    }

    const result = { sourceBytes, containerBytes: container.length, gate, blockCount, encoderError };
    container.fill(0);
    return result;
  } finally {
    source.fill(0);
  }
}

/**
 * Walks the exact v1 capacity boundary so the ceiling is a measured number
 * rather than one read off a constant.
 */
function runBoundaryProbe(): BoundaryProbe {
  const filename = 'boundary-probe.bin';
  const headerBytes = containerHeaderBytes(filename);
  const largestAccepted = V1_MAX_SERIALIZED_CONTAINER_BYTES - headerBytes;
  return {
    filename,
    containerHeaderBytes: headerBytes,
    v1MaxSerializedContainerBytes: V1_MAX_SERIALIZED_CONTAINER_BYTES,
    largestAcceptedSourceBytes: largestAccepted,
    largestAcceptedSourceMib: largestAccepted / MIB,
    atCeiling: probeSourceSize(filename, largestAccepted),
    oneByteOver: probeSourceSize(filename, largestAccepted + 1),
    rawSizeGateRejectsAtOrAbove: V1_MAX_SERIALIZED_CONTAINER_BYTES,
    nominal32MibRejected: 32 * MIB >= V1_MAX_SERIALIZED_CONTAINER_BYTES,
  };
}

