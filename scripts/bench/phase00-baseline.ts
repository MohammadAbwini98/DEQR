const MIME_TYPE = 'application/octet-stream';

/**
 * Two naming schemes for the same bytes.
 *
 * `natural` uses one base name, so `.xlsx` is one byte longer than the rest.
 * `equalLength` holds the filename to twelve bytes for every extension, which
 * removes that single confound: any remaining difference would have to come
 * from the extension itself.
 */
const EXTENSION_NAME_SETS: Record<'natural' | 'equalLength', Record<string, string>> = {
  natural: {
    '.txt': 'identical-bytes.txt',
    '.pdf': 'identical-bytes.pdf',
    '.zip': 'identical-bytes.zip',
    '.xlsx': 'identical-bytes.xlsx',
    '.bin': 'identical-bytes.bin',
  },
  equalLength: {
    '.txt': 'sample01.txt',
    '.pdf': 'sample01.pdf',
    '.zip': 'sample01.zip',
    '.xlsx': 'sample1.xlsx',
    '.bin': 'sample01.bin',
  },
};

