const MIB = 1024 * 1024;

/** The shipping sender cadence. `src/main/ipc-handlers.ts` emits one frame per tick. */
const SHIPPING_TRANSFER_FPS = 10;

/** Frames sampled when a scenario is too large to encode end to end. */
const ENCODE_SAMPLE_FRAMES = 4_096;

const DEFAULT_SIZES_MIB = [1, 16, 32, 48, 64] as const;
