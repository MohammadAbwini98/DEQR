function gitMetadata(): { head: string | null; dirty: boolean | null } {
  try {
    const head = execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
    const dirty = execFileSync('git', ['status', '--porcelain=v1'], { encoding: 'utf8' }).length > 0;
    return { head, dirty };
  } catch {
    return { head: null, dirty: null };
  }
}

function statistics(values: number[]): { min: number; mean: number; max: number; spreadRatio: number } {
  const min = Math.min(...values);
  const max = Math.max(...values);
  const mean = values.reduce((total, value) => total + value, 0) / values.length;
  return { min, mean, max, spreadRatio: min > 0 ? max / min : 0 };
}

async function main(): Promise<void> {
  const options = parseOptions(process.argv.slice(2));
  const output = resolveOutputPath(options.output);
  const corpusDir = resolve(process.cwd(), '.local-run', 'phase00-corpus');
  await mkdir(corpusDir, { recursive: true });
  await mkdir(resolve(output, '..'), { recursive: true });

  let boundary: BoundaryProbe | null = null;
  if (options.mode === 'all' || options.mode === 'boundary') {
    boundary = runBoundaryProbe();
    console.log(
      `BOUNDARY largestAcceptedSource=${boundary.largestAcceptedSourceBytes}`
      + ` (${boundary.largestAcceptedSourceMib.toFixed(6)} MiB)`
      + ` atCeiling=${boundary.atCeiling.gate}/K=${boundary.atCeiling.blockCount}`
      + ` oneByteOver=${boundary.oneByteOver.gate}/K=${boundary.oneByteOver.blockCount ?? 'throw'}`,
    );
  }

  const capacity: CapacityScenario[] = [];
  if (options.mode === 'all' || options.mode === 'capacity') {
    for (const corpus of ['text', 'random'] as Corpus[]) {
      for (const sizeMib of options.sizesMib) {
        if (typeof global.gc === 'function') global.gc();
        const scenario = await runCapacityScenario(corpus, sizeMib, corpusDir, options.decodeMaxMib * MIB);
        capacity.push(scenario);
        console.log(
          `CAPACITY corpus=${corpus} size=${sizeMib}MiB gate=${scenario.selectionGate}`
          + ` blocks=${scenario.blockCount ?? 'n/a'} encoder=${scenario.encoderConstructed ? 'ok' : 'FAILED'}`
          + ` verify=${scenario.verifyOutcome}`
          + ` peakRss=${(scenario.memoryPeak.rssBytes / MIB).toFixed(1)}MiB`,
        );
      }
    }
  }

  type NameScheme = keyof typeof EXTENSION_NAME_SETS;
  const extensionMatrix: Array<{ nameScheme: NameScheme; sample: number; results: ExtensionSample[] }> = [];
  let blockedProbe: ExtensionSample | null = null;
  if (options.mode === 'all' || options.mode === 'extension') {
    // One buffer, five names. Nothing about the bytes changes between runs.
    const source = buildCorpus('random', options.extensionSizeMib * MIB, 0x1234_5678);
    for (const nameScheme of Object.keys(EXTENSION_NAME_SETS) as NameScheme[]) {
      for (let sample = 0; sample < options.samples; sample += 1) {
        if (typeof global.gc === 'function') global.gc();
        const results: ExtensionSample[] = [];
        // Rotate the running order each sample. Whichever extension goes first
        // absorbs that sample's warm-up cost, so rotation stops a fixed order
        // from masquerading as an extension effect.
        const order = DEFAULT_EXTENSIONS.map((_, index) =>
          DEFAULT_EXTENSIONS[(index + sample) % DEFAULT_EXTENSIONS.length]);
        for (const extension of order) {
          const result = await runExtensionSample(source, extension, EXTENSION_NAME_SETS[nameScheme][extension]);
          results.push(result);
          console.log(
            `EXTENSION scheme=${nameScheme} sample=${sample} ext=${extension}`
            + ` container=${result.containerBytes} blocks=${result.blockCount}`
            + ` endToEnd=${result.endToEndMs.toFixed(1)}ms verify=${result.verifyOutcome}`,
          );
        }
        extensionMatrix.push({ nameScheme, sample, results });
      }
    }
    // A blocked extension is a categorical sender reject, not a slow path.
    blockedProbe = await runExtensionSample(source.subarray(0, 64 * 1024), '.exe', 'probe.exe');
    console.log(`EXTENSION blocked-probe ext=.exe blockedBySender=${blockedProbe.blockedBySender}`);
    source.fill(0);
  }

  const summarizeScheme = (nameScheme: NameScheme) => {
    const entries = extensionMatrix.filter((entry) => entry.nameScheme === nameScheme);
    const results = entries.flatMap((entry) => entry.results);
    return {
      distinctContainerDigestsExcludingFilename:
        [...new Set(results.map((result) => result.containerDigestExcludingFilename))].length,
      distinctBlockCounts: [...new Set(results.map((result) => result.blockCount))],
      distinctContainerByteLengths: [...new Set(results.map((result) => result.containerBytes))],
      distinctFilenameByteLengths: [...new Set(results.map((result) => result.filenameBytes))],
      endToEndMsByExtension: Object.fromEntries(DEFAULT_EXTENSIONS.map((extension) => [
        extension,
        statistics(results.filter((result) => result.extension === extension).map((result) => result.endToEndMs)),
      ])),
    };
  };

  const extensionSummary = extensionMatrix.length
    ? {
      natural: summarizeScheme('natural'),
      equalLength: summarizeScheme('equalLength'),
    }
    : null;

  const evidence = {
    schemaVersion: 1,
    benchmark: 'deqr-phase00-baseline-audit',
    label: options.label,
    generatedAt: new Date().toISOString(),
    environment: {
      node: process.version,
      platform: platform(),
      release: release(),
      arch: arch(),
      totalMemoryBytes: totalmem(),
      gcAvailable: typeof global.gc === 'function',
      ...gitMetadata(),
    },
    shippingConstants: {
      v1FountainBlockSizeBytes: V1_FOUNTAIN_BLOCK_SIZE_BYTES,
      v1MaxBlockCount: V1_MAX_BLOCK_COUNT,
      v1MaxSerializedContainerBytes: V1_MAX_SERIALIZED_CONTAINER_BYTES,
      v1MaxSerializedContainerMib: V1_MAX_SERIALIZED_CONTAINER_BYTES / MIB,
      containerMaxFileSizeBytes: MAX_FILE_SIZE,
      shippingTransferFps: SHIPPING_TRANSFER_FPS,
      opticalPayloadBytesPerSecond: SHIPPING_TRANSFER_FPS * V1_FOUNTAIN_BLOCK_SIZE_BYTES,
    },
    configuration: {
      mode: options.mode,
      sizesMib: options.sizesMib,
      samples: options.samples,
      decodeMaxMib: options.decodeMaxMib,
      extensionSizeMib: options.extensionSizeMib,
      corpora: ['text (redundant, gzip-friendly)', 'random (LCG, high entropy)'],
      source: 'deterministic synthetic bytes generated by this script; no payload bytes are recorded',
      delivery: 'in-process desktop encoder into the browser-safe ReceiverSession; no camera, no display, no network',
    },
    boundary,
    capacity,
    extensionMatrix,
    extensionSummary,
    blockedExtensionProbe: blockedProbe,
  };

  await writeFile(output, `${JSON.stringify(evidence, null, 2)}\n`, 'utf8');
  console.log(
    `PHASE00_BASELINE_COMPLETE capacity=${capacity.length}`
    + ` extensionSamples=${extensionMatrix.length} output=${relative(process.cwd(), output)}`,
  );
}

void main().catch((error: unknown) => {
  console.error(`PHASE00_BASELINE_FAILED ${errorMessage(error)}`);
  process.exitCode = 1;
});
